    "img/logo.png",
    "C:\\x.png",
    "C:/x.png",
    "c:\\x.png",
    "1:\\x.png",
    "C:x.png",
    "C:",
    "C:\\",
    "C:/",
    "\\x.png",
    "\\\\srv\\share\\x.png",
    "//srv/share/x.png",
    "\\\\srv\\share",
    "\\\\srv",
    "\\\\",
    "//",
    "///x.png",
    "\\\\?\\C:\\x.png",
    "\\\\.\\C:\\x.png",
    "a\\..\\b.png",
    "a\\.\\b.png",
    "..\\b.png",
    "a\\..",
    "a/../b.png",
    "C:..",
    "\\:\\.\\a",
    "\\:\\.\\.",
    "\\:\\\\a",
    "\\:/./a",
    "\\:\\a\\..",
    "x\\:\\a",
    "C:\\.",
